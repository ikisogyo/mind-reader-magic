const fs=require('fs'),assert=require('assert');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const start=html.indexOf('function onCue(text){'),end=html.indexOf('function onPartialCue(text){',start);
assert(start>=0&&end>start,'final cue handler exists');
const final=html.slice(start,end);
assert(final.includes('specialCuePosition(text)'),'special cue has a normalized transcript position');
assert(final.includes('specialPosition>=lastCuePosition'),'special cue wins only when it is later than normal cue');
assert(final.includes('matchesSpecialCue(text)'),'fuzzy special-cue fallback remains');
const ps=html.indexOf('function onPartialCue(text){'),pe=html.indexOf('function prepareReveal(){',ps);
assert(ps>=0&&pe>ps,'partial handler exists');
const partial=html.slice(ps,pe);
assert(!partial.includes('matchesSpecialCue(text)'),'partial recognition cannot trigger special photo prematurely');
assert(!partial.includes("pending={kind:'special'}"),'partial results do not set special reveal pending');
console.log('v208 special cue ordering: 6 checks passed');
