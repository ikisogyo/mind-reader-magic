const fs=require('fs'),assert=require('assert');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const start=html.indexOf('async function retrieveItemImage'),end=html.indexOf('function retrieveImagesForNewItems',start);
assert(start>=0&&end>start,'image lookup function found');
const fn=html.slice(start,end);
assert(fn.includes('画像を自動取得できません'),'manual image registration fallback is stated clearly');
assert(fn.includes('Google画像検索から探し'),'fallback directs user to Google Images');
assert(fn.includes('link.href=url'),'Google Images link is created from the Japanese item name');
assert(!fn.includes('commons.wikimedia.org')&&!fn.includes('translate'),'lookup has no Wikimedia or translation dependency');
console.log('v202 Japanese Google search fallback: 4 checks passed');
